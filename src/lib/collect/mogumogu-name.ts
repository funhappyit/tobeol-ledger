/**
 * 치환 전 글자 고르기.
 *
 * 전각 영숫자와 반각 가나를 반각/전각으로 모은다.
 * 이걸 안 하면 `Ｔシャツ` 가 사전의 `Tシャツ` 와 다른 말이 되어 그대로 남는다.
 */
export function normalizeMogumoguName(name: string): string {
  return (
    name
      // 전각 영숫자 -> 반각 (Ｔ -> T, １ -> 1)
      .replace(/[Ａ-Ｚａ-ｚ０-９]/g, (ch) => String.fromCharCode(ch.charCodeAt(0) - 0xfee0))
      // 반각 가나 -> 전각 (ﾐﾆ -> ミニ). 조합용 반각 탁점·반탁점은 앞 글자에 붙지 않고 떠 있다
      .replace(/[ｦ-ﾝ]/g, (ch) => HALFWIDTH_KANA[ch] ?? ch)
      // 떠 있는 반각 반탁점·탁점(`マグカップﾟ`)은 글자가 아니라 흔적이라 지운다
      .replace(/[ﾞﾟ]/g, '')
      .replace(/\u3000/g, ' ')
      .replace(/\s+/g, ' ')
      .trim()
  );
}


